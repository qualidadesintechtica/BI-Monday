-- Mantém o bucket privado e todas as versões/fontes existentes. Reaplicável.
begin;
do $$ begin
  if to_regclass('public.pq_projetos_edicoes') is null
     or to_regclass('storage.objects') is null then
    raise exception 'Instale primeiro o editor e o armazenamento das evidências.';
  end if;
end $$;

create table if not exists public.pq_evidencias_compartilhadas (
  id bigint generated by default as identity primary key,
  token_hash text not null unique check(token_hash ~ '^[0-9a-f]{64}$'),
  edicao_id text not null,
  storage_path text not null,
  arquivo_nome text not null,
  mime_type text,
  criado_por uuid not null,
  criado_em timestamptz not null default now(),
  revogado_em timestamptz
);
create index if not exists pq_evidencias_compartilhadas_edicao_idx
  on public.pq_evidencias_compartilhadas(edicao_id) where revogado_em is null;
alter table public.pq_evidencias_compartilhadas enable row level security;
revoke all on public.pq_evidencias_compartilhadas from public,anon,authenticated;
revoke all on sequence public.pq_evidencias_compartilhadas_id_seq from public,anon,authenticated;

create or replace function public.pq_emitir_links_evidencias(p_edicao_id text)
returns jsonb language plpgsql security definer set search_path='' as $$
declare
  v_id public.pq_projetos_edicoes.id%type;
  v_edicao public.pq_projetos_edicoes%rowtype;
  v_item jsonb; v_path text; v_nome text; v_token text;
  v_resultado jsonb := '[]'::jsonb;
begin
  if auth.uid() is null or lower(coalesce(auth.jwt()->>'email','')) !~ '^[^@[:space:]]+@animaeducacao[.]com[.]br$' then
    raise exception 'Acesso institucional necessário para emitir links.' using errcode='42501';
  end if;
  if p_edicao_id is null or length(p_edicao_id)>100 then raise exception 'Versão inválida.'; end if;
  v_id := p_edicao_id;
  perform pg_advisory_xact_lock(hashtextextended('pq_pdf:'||v_id::text,0));
  select * into v_edicao from public.pq_projetos_edicoes where id=v_id;
  if v_edicao.id is null then raise exception 'Versão salva não localizada.'; end if;
  for v_item in select value from jsonb_array_elements(case when jsonb_typeof(v_edicao.evidencias)='array' then v_edicao.evidencias else '[]'::jsonb end) loop
    if lower(coalesce(v_item->>'incluir_relatorio','true')) in ('false','0') then continue; end if;
    v_path := btrim(coalesce(v_item->>'storage_path',''));
    if v_path='' then continue; end if;
    if length(v_path)>2000 or v_path ~ '(^/|(^|/)\.\.(/|$)|[[:cntrl:]])' or position(chr(92) in v_path)>0 then
      raise exception 'Caminho de evidência inválido na versão.';
    end if;
    if not exists(select 1 from storage.objects where bucket_id='pq-evidencias' and name=v_path) then
      raise exception 'Arquivo da evidência não localizado: %',coalesce(v_item->>'arquivo_nome',v_path);
    end if;
    v_nome := coalesce(nullif(btrim(v_item->>'arquivo_nome'),''),reverse(split_part(reverse(v_path),'/',1)),'evidencia');
    v_token := replace(gen_random_uuid()::text||gen_random_uuid()::text,'-','');
    insert into public.pq_evidencias_compartilhadas(token_hash,edicao_id,storage_path,arquivo_nome,mime_type,criado_por)
      values(encode(sha256(convert_to(v_token,'UTF8')),'hex'),v_id::text,v_path,v_nome,v_item->>'mime_type',auth.uid());
    v_resultado := v_resultado||jsonb_build_array(jsonb_build_object('storage_path',v_path,'arquivo_nome',v_nome,'token',v_token));
  end loop;
  return v_resultado;
end $$;

-- Somente a função de servidor pode resolver um token. O navegador anônimo
-- não ganha SELECT nas versões, nos caminhos, na tabela de tokens ou no bucket.
create or replace function public.pq_resolver_evidencia_compartilhada(p_token text)
returns jsonb language plpgsql security definer set search_path='' as $$
declare v_link public.pq_evidencias_compartilhadas%rowtype;
begin
  if p_token is null or p_token !~ '^[0-9a-f]{64}$' then return null; end if;
  select * into v_link from public.pq_evidencias_compartilhadas
    where token_hash=encode(sha256(convert_to(p_token,'UTF8')),'hex') and revogado_em is null;
  if v_link.id is null then return null; end if;
  if not exists(
    select 1 from public.pq_projetos_edicoes e
    cross join lateral jsonb_array_elements(case when jsonb_typeof(e.evidencias)='array' then e.evidencias else '[]'::jsonb end) i
    where e.id::text=v_link.edicao_id and i->>'storage_path'=v_link.storage_path
      and lower(coalesce(i->>'incluir_relatorio','true')) not in ('false','0')
  ) then return null; end if;
  return jsonb_build_object('storage_path',v_link.storage_path,'arquivo_nome',v_link.arquivo_nome,'mime_type',v_link.mime_type);
end $$;

create or replace function public.pq_revogar_links_evidencias(p_edicao_id text)
returns integer language plpgsql security definer set search_path='' as $$
declare v_id public.pq_projetos_edicoes.id%type; v_total integer;
begin
  if auth.uid() is null or lower(coalesce(auth.jwt()->>'email','')) !~ '^[^@[:space:]]+@animaeducacao[.]com[.]br$' then
    raise exception 'Acesso institucional necessário para desativar links.' using errcode='42501';
  end if;
  if p_edicao_id is null or length(p_edicao_id)>100 then raise exception 'Versão inválida.'; end if;
  v_id := p_edicao_id;
  perform pg_advisory_xact_lock(hashtextextended('pq_pdf:'||v_id::text,0));
  if not exists(select 1 from public.pq_projetos_edicoes where id=v_id) then raise exception 'Versão não localizada.'; end if;
  update public.pq_evidencias_compartilhadas set revogado_em=now() where edicao_id=v_id::text and revogado_em is null;
  get diagnostics v_total=row_count;
  return v_total;
end $$;

revoke all on function public.pq_emitir_links_evidencias(text),public.pq_revogar_links_evidencias(text),public.pq_resolver_evidencia_compartilhada(text) from public,anon,authenticated;
grant execute on function public.pq_emitir_links_evidencias(text),public.pq_revogar_links_evidencias(text) to authenticated;
grant execute on function public.pq_resolver_evidencia_compartilhada(text) to service_role;
notify pgrst,'reload schema';
commit;
