alter table public.pq_projetos enable row level security;
alter table public.pq_tarefas enable row level security;
alter table public.pq_importacao_linhas enable row level security;
alter table public.pq_projetos_snapshots enable row level security;

comment on table public.pq_importacoes is
  'Historico e auditoria das planilhas importadas.';
comment on table public.pq_projetos is
  'Estado atual dos projetos recebidos do Ajure.';
comment on table public.pq_tarefas is
  'Estado atual das tarefas e Action Plans recebidos do Ajure.';
comment on table public.pq_importacao_linhas is
  'Linhas brutas recebidas em cada importacao, inclusive erros.';
comment on table public.pq_projetos_snapshots is
  'Fotografia historica dos projetos em cada importacao.';

-- Resultado final esperado: cinco linhas, todas com existe = true.
select
  nome_tabela,
  to_regclass('public.' || nome_tabela) is not null as existe
from unnest(array[
  'pq_importacoes',
  'pq_projetos',
  'pq_tarefas',
  'pq_importacao_linhas',
  'pq_projetos_snapshots'
]) as verificacao(nome_tabela)
order by nome_tabela;
